# print() digunakan untuk menampilkan informasi ke layar.
print("Halo, teman-teman!")
print(2026)
print(10 + 5)  # Ekspresi matematika juga bisa langsung ditampilkan.

# Komentar adalah catatan untuk pembaca kode. Python mengabaikannya.
# Komentar satu baris diawali tanda pagar (#).

"""
Komentar beberapa baris dapat ditulis menggunakan tiga tanda kutip.
Bentuk ini juga sering dipakai sebagai docstring untuk dokumentasi.
"""

# Secara default, print() mengakhiri output dengan baris baru.
print("Belajar", "Python", "itu", "menyenangkan")

# Parameter sep mengatur pemisah antar nilai.
print("2026", "11", "11", sep="-")

# Parameter end mengatur karakter di akhir output.
print("Halo", end=" ")
print("semua!")

