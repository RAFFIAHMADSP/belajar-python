# Operator aritmatika digunakan untuk melakukan perhitungan matematika.

a = 10
b = 3

print("Penjumlahan       :", a + b)   # 13
print("Pengurangan       :", a - b)   # 7
print("Perkalian         :", a * b)   # 30
print("Pembagian         :", a / b)   # 3.333...
print("Pembagian bulat   :", a // b)  # 3
print("Sisa bagi/modulus :", a % b)   # 1
print("Pangkat           :", a ** b)  # 1000

# Operator += adalah bentuk singkat dari x = x + nilai.
total = 0
total += 5
print("Total setelah += 5:", total)

total -= 2  # Sama dengan total = total - 2.
print("Total setelah -= 2:", total)

# Contoh menghitung luas persegi panjang.
panjang = 8
lebar = 4
luas = panjang * lebar
print("Luas persegi panjang:", luas)

